# se cria lista usando o construtor list, range ou colocando os itens entre colchetes, separados por ,
# são mutáveis, pode mudar os elementos
# não é obrigatório declarar listas com elementos: []
# o comando list pede um elemento iterável
# range gera valores entre dois elementos
# dá pra colocar vários elementos diferentes na lista: str, int, float ou bool

frutas = ["laranja", "maca", "uva"]
print(frutas)

frutas = []
print(frutas)

letras = list("python")
print(letras)

numeros = list(range(10))
print(numeros)

carro = ["Ferrari", "F8", 4200000, 2020, 2900, "São Paulo", True]
print(carro)

